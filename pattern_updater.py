# -*- coding: utf-8 -*-
"""
OpenSteamTool pattern TOML 自动更新器.

思路:
  1. 下载最新 Steam 版本的 steamclient64.dll / steamui.dll
  2. 计算 SHA-256, 查 steam-monitor 上游有没有现成 TOML
  3. 上游没有? 用本地已有的旧 TOML 里的 sig 作为 pattern,
     在新 DLL 里做字节匹配 → 找到新 RVA
  4. 输出新 TOML, 推到自己的 fork

用法:
  python pattern_updater.py --dll steamclient64.dll --old_toml old.toml --out new.toml

GitHub Actions 工作流示例见 .github/workflows/update_patterns.yml
"""

import argparse, hashlib, os, re, struct, sys, urllib.request

# =============================================================================
# FNV-1a 32-bit (与 OpenSteamTool 一致)
# =============================================================================
def fnv1a_32(name):
    h = 0x811c9dc5
    for b in name.encode('utf-8'):
        h ^= b
        h = (h * 0x01000193) & 0xFFFFFFFF
    return h

# =============================================================================
# 读 TOML (手写, 避免 tomlplusplus 依赖在 CI 里出问题)
# =============================================================================
def parse_toml(path):
    """返回 [(hex_key, {name, rva, sig}), ...]"""
    entries = {}
    current_key = None
    with open(path, 'r', encoding='utf-8') as f:
        for raw in f:
            line = raw.strip()
            if not line or line.startswith('#'):
                continue
            m = re.match(r'^\[(0x[0-9a-fA-F]+)\]$', line)
            if m:
                current_key = int(m.group(1), 16)
                entries[current_key] = {}
                continue
            m = re.match(r'^(\w+)\s*=\s*"(.+)"$', line)
            if m and current_key is not None:
                entries[current_key][m.group(1)] = m.group(2)
    return entries

# =============================================================================
# 解析 sig → (bytes, mask)   mask[i]=1 表示该字节必须匹配
# =============================================================================
def parse_sig(sig_str):
    bs = []; mask = []
    i = 0
    while i < len(sig_str):
        c = sig_str[i]
        if c in ' \t':
            i += 1; continue
        if c == '?' and i+1 < len(sig_str) and sig_str[i+1] == '?':
            bs.append(0); mask.append(0); i += 2; continue
        if c in '?,': i += 1; continue
        hex_byte = sig_str[i:i+2]
        try:
            bs.append(int(hex_byte, 16)); mask.append(1)
        except ValueError:
            bs.append(0); mask.append(0)
        i += 2
    return bytes(bs), bytes(mask)

# =============================================================================
# 在 DLL 原始字节里搜索 pattern
# =============================================================================
def scan_for_sig(dll_bytes, sig_str):
    bs, mask = parse_sig(sig_str)
    if not bs:
        return None
    plen = len(bs)
    # 字节搜索 (可以用 Boyer-Moore 加速, 但 Steam DLL 就 ~20MB, 纯 Python 够快)
    for i in range(0, len(dll_bytes) - plen + 1):
        ok = True
        for j in range(plen):
            if mask[j] and dll_bytes[i+j] != bs[j]:
                ok = False; break
        if ok:
            return i   # file offset
    return None

# =============================================================================
# 下载上游 TOML
# =============================================================================
def fetch_upstream(sha256, component):
    url = "https://raw.githubusercontent.com/OpenSteam001/steam-monitor/pattern/%s/%s.toml" % (component, sha256)
    try:
        req = urllib.request.Request(url, headers={'User-Agent': 'OpenSteamTool-bot/1.0'})
        with urllib.request.urlopen(req, timeout=15) as r:
            return r.read().decode('utf-8'), url
    except Exception as e:
        return None, str(e)

def fetch_ipc_upstream(sha256):
    url = "https://raw.githubusercontent.com/OpenSteam001/steam-monitor/ipc/steamclient/%s.toml" % sha256
    try:
        req = urllib.request.Request(url, headers={'User-Agent': 'OpenSteamTool-bot/1.0'})
        with urllib.request.urlopen(req, timeout=15) as r:
            return r.read().decode('utf-8'), url
    except Exception as e:
        return None, str(e)

# =============================================================================
# 写 TOML
# =============================================================================
def write_toml(entries, path, header='# MACHINE-GENERATED by pattern_updater.py - do not hand-edit'):
    lines = [header, '']
    for key in sorted(entries.keys()):
        e = entries[key]
        if not e: continue
        lines.append('[0x%08X]' % key)
        if 'name' in e: lines.append('name = "%s"' % e['name'])
        if 'rva'  in e: lines.append('rva  = "0x%X"' % e['rva'])
        if 'sig'  in e: lines.append('sig  = "%s"' % e['sig'])
        lines.append('')
    with open(path, 'w', encoding='utf-8') as f:
        f.write('\n'.join(lines))

# =============================================================================
# 主流程
# =============================================================================
def generate_from_scratch(dll_path, component):
    """从 DLL 文件头 + steam-monitor 现有 TOML 反推 (sig 自匹配)"""
    with open(dll_path, 'rb') as f:
        dll_bytes = f.read()

    sha256 = hashlib.sha256(dll_bytes).hexdigest()
    print("[+] SHA-256: %s" % sha256)

    # 0. 先查上游有没有现成的
    upstream_body, upstream_src = fetch_upstream(sha256, component)
    if upstream_body:
        print("[+] Upstream hit! Saving %s.toml directly" % sha256)
        return sha256, upstream_body

    print("[!] Upstream miss (%s) — building from last-known-good..." % upstream_src)

    # 1. 找本地已有的旧 TOML
    old_toml_path = find_old_toml(component)
    if not old_toml_path:
        print("[!] No old TOML anywhere. Abort (need IDA manual first run).")
        return sha256, None
    print("[+] Using seed: %s" % old_toml_path)

    old_entries = parse_toml(old_toml_path)
    new_entries = {}
    hits = 0; misses = 0

    for hash_key, entry in old_entries.items():
        sig = entry.get('sig', '')
        name = entry.get('name', 'unknown')
        if not sig:
            misses += 1; continue
        fo = scan_for_sig(dll_bytes, sig)
        if fo is None:
            misses += 1
            print("  [MISS] %s — sig not found in new DLL" % name)
            continue
        # file offset → RVA: 读 PE 头
        rva = fileoff_to_rva(dll_bytes, fo)
        if rva is None:
            misses += 1; continue
        new_entries[hash_key] = {'name': name, 'rva': rva, 'sig': sig}
        hits += 1
        print("  [OK]  %-42s 0x%08X" % (name, rva))

    print("[+] %d/%d functions relocated" % (hits, hits + misses))

    # 2. 输出
    out_lines = ['# MACHINE-GENERATED by pattern_updater.py - do not hand-edit', '']
    for key in sorted(new_entries.keys()):
        e = new_entries[key]
        out_lines.append('[0x%08X]' % key)
        out_lines.append('name = "%s"' % e['name'])
        out_lines.append('rva  = "0x%X"' % e['rva'])
        out_lines.append('sig  = "%s"' % e['sig'])
        out_lines.append('')

    return sha256, '\n'.join(out_lines)

def fileoff_to_rva(dll_bytes, fo):
    """PE 头解析: file offset → RVA"""
    # DOS header + e_lfanew
    e_lfanew = struct.unpack_from('<I', dll_bytes, 0x3C)[0]
    # PE signature + COFF header
    machine, num_sections, _, _, _, opt_header_size, chars = struct.unpack_from('<HHIIIHH', dll_bytes, e_lfanew + 4)
    opt_start = e_lfanew + 4 + 20  # PE sig + COFF
    # 可选 header: Section Table 从 opt_start + opt_header_size 开始
    sec_table = opt_start + opt_header_size
    for i in range(num_sections):
        off = sec_table + i * 40
        sec_name = dll_bytes[off:off+8]
        sec_vsize, sec_vaddr, sec_rsize, sec_roff = struct.unpack_from('<IIII', dll_bytes, off + 8)
        if fo >= sec_roff and fo < sec_roff + sec_rsize:
            return sec_vaddr + (fo - sec_roff)
    return None

def find_old_toml(component):
    """在 opensteamtool/pattern/<component>/ 下找任何 .toml"""
    here = os.path.dirname(os.path.abspath(__file__))
    # 上级目录找 opensteamtool 缓存
    candidates = [
        os.path.join(here, 'opensteamtool', 'pattern', component),
        os.path.join(here, 'pattern_cache', component),
        os.path.join(here, 'old'),
    ]
    for d in candidates:
        if os.path.isdir(d):
            for fn in os.listdir(d):
                if fn.endswith('.toml'):
                    return os.path.join(d, fn)
    # 再退一层, 看 Steam 目录 (常见 C:\steam\opensteamtool\pattern\...)
    steam_root = r'C:\steam'
    if os.path.isdir(steam_root):
        d = os.path.join(steam_root, 'opensteamtool', 'pattern', component)
        if os.path.isdir(d):
            for fn in os.listdir(d):
                if fn.endswith('.toml'):
                    return os.path.join(d, fn)
    return None

# =============================================================================
# CLI
# =============================================================================
if __name__ == '__main__':
    ap = argparse.ArgumentParser()
    ap.add_argument('--dll', required=True)
    ap.add_argument('--component', required=True, choices=['steamclient','steamui'])
    ap.add_argument('--out_dir', default='./output')
    args = ap.parse_args()

    sha, body = generate_from_scratch(args.dll, args.component)
    if not body:
        sys.exit(1)

    os.makedirs(args.out_dir, exist_ok=True)
    out_path = os.path.join(args.out_dir, 'pattern', args.component, sha + '.toml')
    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    with open(out_path, 'w', encoding='utf-8') as f:
        f.write(body)
    print("[+] Saved → %s" % out_path)
